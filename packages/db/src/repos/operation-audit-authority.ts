const captureIssuedPrefix = async (plan: Readonly<IssuedLifecycleAppendPlan>, directory: string): Promise<IssuedCapture> => {
  requireRoot()
  if (!isAbsolute(directory) || resolve(directory) !== directory || await realpath(directory) !== directory
    || directory === '/var/lib/xpanel' || directory.startsWith('/var/lib/xpanel/')) return unavailable('issued_directory_invalid')
  const pins: ReadonlyAuditPin[] = [], absent: string[] = []
  const check = async (pin: ReadonlyAuditPin): Promise<void> => {
    const named = await lstat(pin.path, { bigint: true }), held = await pin.handle.stat({ bigint: true })
    if (named.isSymbolicLink() || !sameReadonlyStat(pin.initial, named) || !sameReadonlyStat(pin.initial, held)
      || await realpath(pin.path) !== pin.path) return unavailable('issued_pin_changed')
  }
  const bytes = async (pin: ReadonlyAuditPin, maximum: number): Promise<Buffer> => {
    await check(pin)
    if (pin.initial.size < 0n || pin.initial.size > BigInt(maximum)) return unavailable('issued_file_size')
    const value = Buffer.alloc(Number(pin.initial.size)); let offset = 0
    while (offset < value.length) { const read = await pin.handle.read(value, offset, value.length - offset, offset); if (!read.bytesRead) return unavailable('issued_short_read'); offset += read.bytesRead }
    await check(pin); return value
  }
  const file = async (path: string, mode: bigint, maximum: number, optional = false): Promise<ReadonlyAuditPin | null> => {
    let handle: FileHandle
    try { handle = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW) }
    catch (error) { if (optional && (error as NodeJS.ErrnoException).code === 'ENOENT') { absent.push(path); return null } throw error }
    let initial: BigIntStats
    try { initial = await handle.stat({ bigint: true }) } catch (error) { await handle.close(); throw error }
    const pin = { path, handle, initial } as ReadonlyAuditPin; pins.push(pin)
    if (!initial.isFile() || initial.uid !== 0n || initial.gid !== 0n || initial.nlink !== 1n || (initial.mode & 0o7777n) !== mode) return unavailable('issued_file_permissions')
    pin.bytes = await bytes(pin, maximum); return pin
  }
  const close = async (): Promise<void> => {
    const results = await Promise.allSettled(pins.splice(0).reverse().map(pin => pin.handle.close()))
    const failures = results.filter(item => item.status === 'rejected')
    if (failures.length) throw new AggregateError(failures.map(item => item.reason), 'issued audit pins did not retire')
  }
  try {
    await validateDirectory(directory)
    for (let path = directory; ; path = dirname(path)) {
      const handle = await open(path, constants.O_RDONLY | constants.O_DIRECTORY | constants.O_NOFOLLOW)
      let initial: BigIntStats
      try { initial = await handle.stat({ bigint: true }) } catch (error) { await handle.close(); throw error }
      const pin = { path, handle, initial }; pins.push(pin)
      if (!initial.isDirectory() || initial.uid !== 0n || (initial.mode & 0o022n) !== 0n) return unavailable('issued_ancestry_permissions')
      await check(pin); if (dirname(path) === path) break
    }
    if (!equalIdentity(identity(pins[0]!.initial), plan.priorAnchor.directoryIdentity)) return unavailable('issued_directory_identity')
    const mutexPath = join(directory, '.writer-mutex.sqlite'), mutex = await lstat(mutexPath, { bigint: true })
    if (!mutex.isFile() || mutex.isSymbolicLink() || mutex.nlink !== 1n || mutex.uid !== 0n || mutex.gid !== 0n || (mutex.mode & 0o7777n) !== 0o660n
      || mutex.dev + ':' + mutex.ino !== plan.writer.mutexIdentity) return unavailable('issued_mutex_identity')
    const authority = await file(join(directory, 'authority.json'), 0o640n, 8192)
    if (authority!.bytes!.toString('utf8') !== plan.writer.authorityRaw) return unavailable('issued_authority_changed')
    const log = await file(join(directory, OPERATION_AUDIT_LOG_NAME), 0o600n, MAX_OPERATION_AUDIT_BYTES)
    if (!equalIdentity(identity(log!.initial), plan.priorAnchor.logIdentity)) return unavailable('issued_log_identity')
    const anchor = await file(join(directory, OPERATION_AUDIT_ANCHOR_NAME), 0o600n, MAX_PENDING_BYTES)
    const pending = await file(join(directory, OPERATION_AUDIT_PENDING_NAME), 0o600n, MAX_PENDING_BYTES, true)
    const candidate = await file(join(directory, OPERATION_AUDIT_ANCHOR_NAME) + '.candidate', 0o600n, MAX_PENDING_BYTES, true)
    const lockPath = join(directory, '.lock')
    const lockInfo = await lstat(lockPath, { bigint: true }).catch(error => { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null; throw error })
    if (lockInfo) {
      if (!lockInfo.isDirectory() || lockInfo.isSymbolicLink() || lockInfo.uid !== 0n || lockInfo.gid !== 0n || (lockInfo.mode & 0o7777n) !== 0o2770n) return unavailable('issued_lock_permissions')
      const handle = await open(lockPath, constants.O_RDONLY | constants.O_DIRECTORY | constants.O_NOFOLLOW)
      const pin = { path: lockPath, handle, initial: lockInfo }; pins.push(pin); await check(pin)
      const names = await readdir(lockPath)
      if (names.length !== 1 || names[0] !== 'owner.json') return unavailable('issued_unknown_lock_entries')
      const owner = await file(join(lockPath, 'owner.json'), 0o640n, 8192)
      if (owner!.bytes!.toString('utf8') !== plan.writer.ownerRaw) return unavailable('issued_foreign_owner')
    } else absent.push(lockPath)
    const state = classifyIssuedLifecycleAppend(plan, { log: log!.bytes!, anchor: anchor!.bytes!, pending: pending?.bytes ?? null, candidate: candidate?.bytes ?? null })
    const info = freezeDeep({ plan, state, writerMarker: lockInfo ? 'issued-owner' as const : 'absent' as const })
    const assertCurrent = async (): Promise<void> => {
      for (const path of absent) {
        try { await lstat(path); return unavailable('issued_absence_changed') }
        catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error }
      }
      if ((await readdir(directory)).some(name => name.startsWith('.lock-prepared-') || name === '.writer-mutex.sqlite-init')) return unavailable('issued_unexplained_prepared_guard')
      if (!sameReadonlyStat(mutex, await lstat(mutexPath, { bigint: true }))) return unavailable('issued_mutex_changed')
      for (const pin of pins) {
        await check(pin)
        if (pin.bytes && !(await bytes(pin, pin.bytes.length)).equals(pin.bytes)) return unavailable('issued_bytes_changed')
      }
      if (lockInfo && (await readdir(lockPath)).join('\0') !== 'owner.json') return unavailable('issued_lock_entries_changed')
    }
    await assertCurrent()
    return { info, prior: parseLog(log!.bytes!.subarray(0, plan.priorAnchor.bytes)), assertCurrent, close }
  } catch (error) { await close(); throw error }
}
