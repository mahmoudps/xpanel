const SHELL_METACHAR_RE = /[;&|<>`$(){}[\]*?~#\\\r\n\u0000-\u001f\u007f]/

/**
 * Kernel-level protection against symlink/hardlink race attacks (TOCTOU) in world/group-writable
 * sticky directories and cross-UID ptrace/dmesg leaks.
 */
export const renderSymlinkProtectionSysctl = (): RenderedFile => {
  const lines = [
    '# Generated by xPanel: kernel symlink, hardlink, FIFO, and ptrace isolation.',
    'fs.protected_symlinks = 1',
    'fs.protected_hardlinks = 1',
    'fs.protected_fifos = 2',
    'fs.protected_regular = 2',
    'kernel.yama.ptrace_scope = 2',
    'kernel.dmesg_restrict = 1',
    'kernel.kptr_restrict = 2',
  ]
  return {
    path: SYMLINK_SYSCTL_PATH,
    content: `${lines.join('\n')}\n`,
    mode: 0o644,
    owner: 'root',
    group: 'root',
  }
}

export const symlinkProtectionActions = (): HostAction[] => [
  { kind: 'exec', argv: [SYSCTL_BINARY, '-p', SYMLINK_SYSCTL_PATH] },
]

/**
 * Locks down `/home` (and any extra home base) to `root:root` mode `0711` (execute/traverse only,
 * no directory listing) so Account A cannot `ls /home` to enumerate other accounts or replace
 * an account root directory with a symlink.
 */
export const homeBaseProtectionActions = (homeBases: readonly string[] = ['/home']): HostAction[] => {
  const unique = [...new Set(homeBases.map((b) => assertAbsPath('homeBase', b)))]
  return unique.map((path): HostAction => ({
    kind: 'ensure-dir',
    path,
    mode: 0o711,
    owner: 'root',
    group: 'root',
  }))
}

export interface PathNodeStat {
  path: string
  isSymbolicLink: boolean
  isDirectory: boolean
  uid: number
  gid: number
  mode: number
  /** Resolved target path when `isSymbolicLink === true` */
  realTargetPath?: string
  /** UID of the resolved target when `isSymbolicLink === true` */
  targetUid?: number
}

export interface AccountRootChainInput {
  account: Pick<Account, 'username' | 'uid' | 'gid' | 'home'>
  homeBaseStat: PathNodeStat
  accountRootStat: PathNodeStat
  subpathStats?: readonly PathNodeStat[]
}

/**
 * Verifies the entire filesystem stat chain from the home base (`/home`) through the account root
 * (`/home/<user>`) down to any target subpath before the root agent or file manager touches it.
 */
export const assertSafeAccountRootChain = (input: AccountRootChainInput): void => {
  const id = assertAccountIdentity(input.account)
  const { home, base } = assertAccountHome(input.account.home, id.username)

  const hb = input.homeBaseStat
  if (hb.isSymbolicLink) {
    fail('FORBIDDEN', `home base ${base} is a symbolic link; refusing operation`, { path: base })
  }
  if (!hb.isDirectory) {
    fail('FORBIDDEN', `home base ${base} is not a directory`, { path: base })
  }
  if (hb.uid !== 0 || hb.gid !== 0) {
    fail('FORBIDDEN', `home base ${base} must be owned by root:root (found ${hb.uid}:${hb.gid})`, {
      path: base,
      uid: hb.uid,
      gid: hb.gid,
    })
  }
  if ((hb.mode & 0o022) !== 0) {
    fail('FORBIDDEN', `home base ${base} must not be group- or world-writable`, {
      path: base,
      mode: hb.mode & 0o777,
    })
  }

  const root = input.accountRootStat
  if (root.isSymbolicLink) {
    fail('FORBIDDEN', `account root ${home} is a symbolic link; refusing to traverse`, {
      username: id.username,
      path: home,
    })
  }
  if (!root.isDirectory) {
    fail('FORBIDDEN', `account root ${home} is not a directory`, {
      username: id.username,
      path: home,
    })
  }
  if (root.uid !== id.uid && root.uid !== 0) {
    fail('FORBIDDEN', `account root ${home} owner UID ${root.uid} does not match account UID ${id.uid}`, {
      username: id.username,
      expectedUid: id.uid,
      actualUid: root.uid,
    })
  }
  if ((root.mode & 0o027) !== 0) {
    fail('FORBIDDEN', `account root ${home} has unsafe permissions (mode 0${(root.mode & 0o777).toString(8)}); must be 0750 or stricter`, {
      username: id.username,
      mode: root.mode & 0o777,
    })
  }

  for (const node of input.subpathStats ?? []) {
    if (!node.path.startsWith(`${home}/`) && node.path !== home) {
      fail('FORBIDDEN', `path ${node.path} is outside account root ${home}`, { path: node.path, home })
    }
    if (node.isSymbolicLink) {
      const target = node.realTargetPath
      if (!target || (!target.startsWith(`${home}/`) && target !== home)) {
        fail('FORBIDDEN', `symlink ${node.path} points outside account root ${home}`, {
          path: node.path,
          target: target ?? null,
        })
      }
      if (node.targetUid !== id.uid) {
        fail('FORBIDDEN', `symlink ${node.path} target UID ${String(node.targetUid)} does not match account UID ${id.uid} (SymLinksIfOwnerMatch)`, {
          path: node.path,
          targetUid: node.targetUid ?? null,
          expectedUid: id.uid,
        })
      }
    } else if (node.uid !== id.uid && node.uid !== 0) {
      fail('FORBIDDEN', `path ${node.path} owner UID ${node.uid} does not match account UID ${id.uid}`, {
        path: node.path,
        actualUid: node.uid,
        expectedUid: id.uid,
      })
    }
  }
}

/**
 * Renders the `/opt/xpanel/bin/jailshell` wrapper script installed on the host.
 * Even when invoked as a login shell by sshd, the account lands in its own cgroup slice
 * with an isolated environment and restricted umask `0027`.
 */
export const renderJailShellBinary = (jailShellPath = DEFAULT_JAIL_SHELL): RenderedFile => {
  const path = assertAbsPath('jailShellPath', jailShellPath)
  const lines = [
    '#!/bin/sh',
    '# Generated by xPanel: isolated jailed shell wrapper for account logins.',
    'set -eu',
    'umask 0027',
    'if [ "$(id -u)" -lt 20000 ] || [ "$(id -u)" -gt 60000 ]; then',
    '  echo "xPanel jailshell: account UID must be in 20000..60000" >&2',
    '  exit 1',
    'fi',
    'case "${HOME:-}" in',
    '  /home/*|/home[0-9]*/*) ;;',
    '  *) echo "xPanel jailshell: invalid HOME" >&2; exit 1 ;;',
    'esac',
    'if [ -L "$HOME" ]; then',
    '  echo "xPanel jailshell: account root is a symlink; refusing login" >&2',
    '  exit 1',
    'fi',
    'export TMPDIR="$HOME/tmp"',
    'export TMP="$HOME/tmp"',
    'export TEMP="$HOME/tmp"',
    'export PATH="/usr/local/bin:/usr/bin:/bin"',
    'cd "$HOME"',
    'exec /bin/bash --norc --noprofile --restricted "$@"',
  ]
  return {
    path,
    content: `${lines.join('\n')}\n`,
    mode: 0o755,
    owner: 'root',
    group: 'root',
  }
}

export interface JailedCommandOptions {
  /** Relative working directory inside the account home (default: '') */
  cwdRel?: string
  /** Optional environment variables (merged with account userdata environmentVars) */
  env?: Record<string, string>
  /** Extra home bases to hide via TemporaryFileSystem=:ro */
  homeBases?: string[]
}

/**
 * Parses and validates a jailed command into an explicit `[resolvedBinary, ...args]` vector.
 * Refuses shell metacharacters, `sh`/`bash`, `-c`, and any binary not in `ALLOWED_JAIL_BINARIES`.
 */
export const parseAndValidateJailedCommand = (command: string | readonly string[]): string[] => {
  let tokens: string[]
  if (typeof command === 'string') {
    const trimmed = command.trim()
    if (!trimmed || trimmed.length > 4096) {
      return invalid('jailed command must be a non-empty string up to 4096 chars')
    }
    if (SHELL_METACHAR_RE.test(trimmed)) {
      fail('VALIDATION', 'jailed command contains forbidden shell metacharacters; pass a single command and arguments', {
        command: trimmed.slice(0, 128),
      })
    }
    tokens = trimmed.split(/\s+/).filter(Boolean)
  } else if (Array.isArray(command) && command.length > 0 && command.length <= 64) {
    tokens = command.map((t) => {
      if (typeof t !== 'string' || t.length === 0 || t.length > 1024 || SHELL_METACHAR_RE.test(t)) {
        fail('VALIDATION', 'jailed command argument contains forbidden shell metacharacters', { arg: String(t).slice(0, 64) })
      }
      return t
    })
  } else {
    return invalid('jailed command must be a non-empty string or argv array')
  }

  const head = tokens[0]!
  const resolvedBin = ALLOWED_JAIL_BINARIES[head]
  if (!resolvedBin) {
    return fail('FORBIDDEN', `binary "${head}" is not permitted in the jailed shell allowlist`, {
      binary: head,
      allowed: Object.keys(ALLOWED_JAIL_BINARIES).filter((k) => !k.startsWith('/')),
    })
  }
  for (const arg of tokens.slice(1)) {
    if (arg === '..' || arg.startsWith('../') || arg.includes('/../') || (arg.startsWith('/') && !arg.startsWith('/home/'))) {
      fail('FORBIDDEN', `argument "${arg}" references a path outside the account home`, { arg })
    }
  }
  return [resolvedBin, ...tokens.slice(1)]
}

const buildSandboxRunPrefix = (
  account: Pick<Account, 'username' | 'uid' | 'gid' | 'home'>,
  opts: JailedCommandOptions = {},
): string[] => {
  const id = assertAccountIdentity(account)
  const { home, base } = assertAccountHome(account.home, id.username, opts.homeBases)
  const cwdRel = (opts.cwdRel ?? '').replace(/^\/+/, '').replace(/\/+$/, '')
  if (cwdRel.split('/').some((seg) => seg === '..' || seg.includes('\u0000') || seg.includes('\\'))) {
    fail('FORBIDDEN', 'working directory cannot traverse outside account home')
  }
  const workDir = cwdRel ? `${home}/${cwdRel}` : home

  const bases = new Set([base, ...(opts.homeBases ?? [])])
  bases.delete('/home')

  const properties = [
    `User=${id.username}`,
    `Group=${id.username}`,
    `Slice=${accountSliceName(id.uid)}`,
    'UMask=0027',
    'PrivateTmp=yes',
    'PrivateDevices=yes',
    'ProtectSystem=strict',
    'ProtectHome=tmpfs',
    ...[...bases].sort().map((b) => `TemporaryFileSystem=${b}:ro`),
    `BindPaths=${home}`,
    `ReadWritePaths=${home}`,
    'ProtectProc=invisible',
    'ProtectKernelTunables=yes',
    'ProtectKernelModules=yes',
    'ProtectKernelLogs=yes',
    'ProtectControlGroups=yes',
    'NoNewPrivileges=yes',
    'RestrictSUIDSGID=yes',
    'RestrictNamespaces=yes',
    'RestrictRealtime=yes',
    'LockPersonality=yes',
    'CapabilityBoundingSet=',
    'AmbientCapabilities=',
    'SocketBindAllow=udp',
    'SocketBindDeny=any',
  ]

  const envFlags: string[] = [
    `--setenv=HOME=${home}`,
    `--setenv=USER=${id.username}`,
    `--setenv=LOGNAME=${id.username}`,
    `--setenv=TMPDIR=${home}/tmp`,
    '--setenv=PATH=/usr/local/bin:/usr/bin:/bin',
  ]
  for (const [k, v] of Object.entries(opts.env ?? {})) {
    if (!/^[A-Za-z_][A-Za-z0-9_]{0,63}$/.test(k) || /[\u0000-\u001f\u007f]/.test(v)) {
      invalid(`invalid environment variable ${k}`)
    }
    envFlags.push(`--setenv=${k}=${v}`)
  }

  return [
    SYSTEMD_RUN_BINARY,
    '--pipe',
    '--wait',
    '--collect',
    '--quiet',
    `--working-directory=${workDir}`,
    ...properties.flatMap((p) => ['--property', p]),
    ...envFlags,
    '--',
  ]
}

/**
 * Builds the `systemd-run` argv that executes an allowed binary and its arguments directly
 * (never `bash -c`) as the account UID inside `xpanel-<uid>.slice` with a private `/tmp`,
 * invisible `/proc` of other users, and a mount namespace where `/home` contains ONLY this
 * account's home directory.
 */
export const buildJailedShellArgv = (
  account: Pick<Account, 'username' | 'uid' | 'gid' | 'home' | 'status' | 'shell'>,
  plan: Pick<Plan, 'name' | 'shell'>,
  command: string | readonly string[],
  opts: JailedCommandOptions = {},
): string[] => {
  assertJailedShellAllowed(account, plan)
  const cmdArgv = parseAndValidateJailedCommand(command)
  return [...buildSandboxRunPrefix(account, opts), ...cmdArgv]
}

/**
 * Builds the `systemd-run` argv to run a file manager operation inside the account's own slice
 * (`xpanel-<uid>.slice`) and UID (`User=<username>`, `Group=<username>`, `ProtectHome=tmpfs`,
 * `BindPaths=<home>`), eliminating root-privilege symlink race conditions.
 */
export const buildJailedFileOpArgv = (
  account: Pick<Account, 'username' | 'uid' | 'gid' | 'home'>,
  opArgv: readonly string[],
  opts: JailedCommandOptions = {},
): string[] => {
  const validated = parseAndValidateJailedCommand(opArgv)
  return [...buildSandboxRunPrefix(account, opts), ...validated]
}

/**
 * Renders the per-domain custom configuration drop-in files (`userdata` model):
 * - `/etc/xpanel/userdata/<user>/<domain>/nginx.conf`
 * - `/etc/xpanel/userdata/<user>/<domain>/apache.conf`
 * - `<docRoot>/.user.ini` (when `userIni` has entries)
 */
export const renderDomainCustomIncludes = (
  account: Pick<Account, 'username' | 'uid' | 'gid' | 'home'>,
  docRoot: string,
  custom: DomainCustomConfig,
  _os?: OsProfile,
): RenderedFile[] => {
  const id = assertAccountIdentity(account)
  const baseDir = `${USERDATA_ROOT}/${id.username}/${custom.domainName}`
  const files: RenderedFile[] = []

  const nginxLines: string[] = [
    `# Managed by xPanel userdata: custom Nginx include for ${custom.domainName} (account ${id.username})`,
  ]
  for (const [header, value] of Object.entries(custom.customHeaders)) {
    nginxLines.push(`add_header ${header} "${value}" always;`)
  }
  for (const path of custom.cacheBypassPaths) {
    nginxLines.push(`location ^~ ${path} { set $xpanel_nocache_custom 1; }`)
  }
  if (custom.nginxInclude.trim()) {
    nginxLines.push(custom.nginxInclude.trim())
  }
  files.push({
    path: `${baseDir}/nginx.conf`,
    content: `${nginxLines.join('\n')}\n`,
    mode: 0o644,
    owner: 'root',
    group: 'root',
  })

  const apacheLines: string[] = [
    `# Managed by xPanel userdata: custom Apache include for ${custom.domainName} (account ${id.username})`,
  ]
  for (const [header, value] of Object.entries(custom.customHeaders)) {
    apacheLines.push(`Header always set ${header} "${value}"`)
  }
  if (custom.apacheInclude.trim()) {
    apacheLines.push(custom.apacheInclude.trim())
  }
  files.push({
    path: `${baseDir}/apache.conf`,
    content: `${apacheLines.join('\n')}\n`,
    mode: 0o644,
    owner: 'root',
    group: 'root',
  })

  const iniEntries = Object.entries(custom.userIni)
  if (iniEntries.length > 0) {
    const iniLines = [
      `; Managed by xPanel userdata for ${custom.domainName}`,
      ...iniEntries.map(([k, v]) => `${k} = ${v}`),
    ]
    files.push({
      path: `${docRoot}/.user.ini`,
      content: `${iniLines.join('\n')}\n`,
      mode: 0o640,
      owner: id.username,
      group: id.username,
    })
  }

  return files
}

/**
 * Renders Postfix sender-dependent outbound IPv4/IPv6 transport maps and master.cf transport
 * definitions so each domain/account can send mail from its own dedicated IP and HELO hostname.
 */
export const renderPostfixOutboundIpTransports = (
  domains: readonly Pick<Domain, 'name' | 'accountId' | 'ipv4' | 'ipv6'>[],
  accountsById: ReadonlyMap<string, Pick<Account, 'id' | 'ipv4' | 'ipv6'>>,
  mailConfig: MailIpConfig,
  serverFallback: { ipv4: string; ipv6?: string | null; hostname: string; postfixDir?: string },
): { files: RenderedFile[]; actions: HostAction[] } => {
  const postfixDir = serverFallback.postfixDir ?? '/etc/postfix'
  const senderLines: string[] = [
    '# Generated by xPanel: per-domain outbound SMTP transport map',
  ]
  const transportsByName = new Map<string, { ipv4: string; ipv6: string | null; heloHostname: string }>()

  const sortedDomains = [...domains].sort((a, b) => a.name.localeCompare(b.name))
  for (const dom of sortedDomains) {
    const acc = accountsById.get(dom.accountId)
    if (!acc) continue
    const resolved = resolveDomainOutboundMailIp(dom, acc, mailConfig, serverFallback)
    senderLines.push(`@${dom.name}  ${resolved.transportName}:`)
    if (!transportsByName.has(resolved.transportName)) {
      transportsByName.set(resolved.transportName, {
        ipv4: resolved.ipv4,
        ipv6: resolved.ipv6,
        heloHostname: resolved.heloHostname,
      })
    }
  }

  const masterLines: string[] = [
    '# Generated by xPanel: outbound SMTP transports with dedicated IPv4/IPv6 bind addresses',
  ]
  for (const [transportName, t] of [...transportsByName.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    masterLines.push(`${transportName} unix - - y - - smtp`)
    masterLines.push(`  -o smtp_bind_address=${t.ipv4}`)
    if (t.ipv6) {
      masterLines.push(`  -o smtp_bind_address6=${t.ipv6}`)
    }
    masterLines.push(`  -o smtp_helo_name=${t.heloHostname}`)
  }

  const senderMapPath = `${postfixDir}/xpanel_sender_transports`
  const masterOutPath = `${postfixDir}/xpanel_master_outbound.cf`

  return {
    files: [
      {
        path: senderMapPath,
        content: `${senderLines.join('\n')}\n`,
        mode: 0o644,
        owner: 'root',
        group: 'root',
      },
      {
        path: masterOutPath,
        content: `${masterLines.join('\n')}\n`,
        mode: 0o644,
        owner: 'root',
        group: 'root',
      },
    ],
    actions: [
      { kind: 'exec', argv: ['/usr/sbin/postmap', senderMapPath] },
    ],
  }
}
