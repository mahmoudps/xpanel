// The private view of an account's SSH login shell. Service, cron and application units get theirs from systemd; a login
// shell starts under sshd, so an unprivileged shell cannot build one. jailshell enters this root script through one sudo rule.
// The script namespaces itself, then drops every privilege before it starts the shell again with no way back.

import type { ConfigTest, RenderedFile, ShellJailPolicy } from '@xpanel/core'
import { DEFAULT_JAIL_SHELL } from './account.ts'
import { assertAbsPath, invalid } from './validate.ts'

export const SHELL_JAIL_ENTER = '/usr/local/sbin/xpanel-jail-enter'
/** Tells the jailshell past the privilege drop that `ssh host command` waits on descriptor 3. */
export const SHELL_JAIL_ARGV_FD = 3
export const SHELL_JAIL_SUDOERS = '/etc/sudoers.d/xpanel-shell-jail'
export const SUDO_BINARY = '/usr/bin/sudo'
export const VISUDO_BINARY = '/usr/sbin/visudo'
/** World-readable paths that describe the host or other accounts. /opt/xpanel/bin stays: it holds the shell. */
const HIDDEN_SYSTEM_PATHS = ['/etc/xpanel', '/var/lib/xpanel', '/var/log', '/var/mail', '/var/spool']

export const shellJailActive = (policy: ShellJailPolicy): boolean => policy.privateTmp || policy.hiddenHomes || policy.systemView

const tmpfs = (path: string, mode: string, size: string): string => `mount -t tmpfs -o mode=${mode},size=${size},nosuid,nodev tmpfs ${path}`

const insideNamespace = (policy: ShellJailPolicy, homeBases: readonly string[]): string[] => [
  'set -eu',
  'uid=$1 gid=$2 user=$3 home=$4',
  ...(policy.hiddenHomes ? [
    'keep=$(mktemp -d /run/xpanel-jail.XXXXXX)',
    'mount --bind "$home" "$keep"',
    ...homeBases.map(base => `[ ! -d ${base} ] || ${tmpfs(base, '0755', '1m')}`),
    'mkdir -p "$home"',
    'mount --move "$keep" "$home"',
    'rmdir "$keep"',
  ] : []),
  ...(policy.privateTmp ? [tmpfs('/tmp', '1777', '256m'), tmpfs('/var/tmp', '1777', '64m')] : []),
  ...(policy.systemView ? [
    'mount -t proc -o hidepid=2,nosuid,nodev,noexec proc /proc',
    ...HIDDEN_SYSTEM_PATHS.map(path => `[ ! -d ${path} ] || ${tmpfs(path, '0755', '1m')}`),
    'view=$(mktemp -d /run/xpanel-jail.XXXXXX)',
    tmpfs('"$view"', '0755', '1m'),
    'getent passwd root "$user" > "$view/passwd"',
    'getent group root "$user" > "$view/group"',
    'mount --bind "$view/passwd" /etc/passwd',
    'mount --bind "$view/group" /etc/group',
    'umount -l "$view"',
    'rmdir "$view"',
  ] : []),
  `exec setpriv --reuid="$uid" --regid="$gid" --init-groups --inh-caps=-all --bounding-set=-all --no-new-privs -- /usr/bin/env -i HOME="$home" USER="$user" LOGNAME="$user" TERM="\${TERM:-dumb}" XPANEL_JAIL_ARGV=${SHELL_JAIL_ARGV_FD} ${DEFAULT_JAIL_SHELL}`,
]

const enterScript = (policy: ShellJailPolicy, homeBases: readonly string[]): string => [
  '#!/bin/sh',
  '# Generated by xPanel: the view of an account login shell. Runs as root through one sudo rule.',
  'set -eu',
  'PATH=/usr/sbin:/usr/bin:/sbin:/bin',
  'uid=${SUDO_UID:-}',
  `case "$uid" in ''|*[!0-9]*) echo "xPanel shell jail: not started through sudo" >&2; exit 1 ;; esac`,
  'if [ "$uid" -lt 20000 ] || [ "$uid" -gt 60000 ]; then',
  '  echo "xPanel shell jail: account UID must be in 20000..60000" >&2',
  '  exit 1',
  'fi',
  'entry=$(getent passwd "$uid")',
  `user=$(printf '%s' "$entry" | cut -d: -f1)`,
  `gid=$(printf '%s' "$entry" | cut -d: -f4)`,
  `home=$(printf '%s' "$entry" | cut -d: -f6)`,
  'case "$home" in /home/*|/home[0-9]*/*) ;; *) echo "xPanel shell jail: invalid home" >&2; exit 1 ;; esac',
  ...(policy.exceptions.length ? [
    `case "$user" in ${policy.exceptions.map(entry => entry.username).join('|')})`,
    `  exec setpriv --reuid="$uid" --regid="$gid" --init-groups --inh-caps=-all --bounding-set=-all --no-new-privs -- /usr/bin/env -i HOME="$home" USER="$user" LOGNAME="$user" TERM="\${TERM:-dumb}" XPANEL_JAIL_ARGV=${SHELL_JAIL_ARGV_FD} ${DEFAULT_JAIL_SHELL} ;;`,
    'esac',
  ] : []),
  `exec unshare --mount --propagation private -- /bin/sh -c '`,
  ...insideNamespace(policy, homeBases),
  `' xpanel-jail "$uid" "$gid" "$user" "$home"`,
  '',
].join('\n')

const sudoers = [
  '# Generated by xPanel. An account enters the view of its login shell through this one command.',
  // closefrom keeps descriptor 3, the only way an account command reaches the shell: the rule itself refuses every argument.
  `Defaults!${SHELL_JAIL_ENTER} !requiretty, !use_pty, !pam_session, !pam_setcred, !syslog, closefrom=${SHELL_JAIL_ARGV_FD + 1}`,
  `ALL ALL=(root) NOPASSWD: ${SHELL_JAIL_ENTER} ""`,
  '',
].join('\n')

/** Nothing is rendered while every switch is off: login shells stay as they are and sudo gains no rule. */
export const renderShellJail = (policy: ShellJailPolicy, homeBases: readonly string[]): { files: RenderedFile[]; tests: ConfigTest[]; active: boolean } => {
  if (!shellJailActive(policy)) return { files: [], tests: [], active: false }
  const bases = [...new Set(homeBases.map(base => assertAbsPath('homeBase', base)))].sort()
  for (const base of bases) if (!/^\/home[0-9]{0,2}$/.test(base)) return invalid('a shell jail hides only home bases', { base })
  for (const entry of policy.exceptions) if (!/^[a-z][a-z0-9]{0,15}$/.test(entry.username)) return invalid('a shell jail exception needs one account username', { username: entry.username })
  return {
    active: true,
    files: [
      { path: SHELL_JAIL_ENTER, content: enterScript(policy, bases), mode: 0o750, owner: 'root', group: 'root' },
      { path: SHELL_JAIL_SUDOERS, content: sudoers, mode: 0o440, owner: 'root', group: 'root' },
    ],
    tests: [{ name: 'sudoers', argv: [VISUDO_BINARY, '-cf', SHELL_JAIL_SUDOERS] }],
  }
}
