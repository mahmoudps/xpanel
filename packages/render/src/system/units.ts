// systemd units for account processes. Every unit runs as the account, inside xpanel-<uid>.slice, in a
// mount namespace where only its own home is visible and the OS is read-only.
//
// Hardening deliberately left out because it breaks real PHP/Node/Python workloads:
// - MemoryDenyWriteExecute=yes: kills PCRE JIT, opcache JIT and V8.
// - SystemCallFilter=@system-service: some PHP extensions and native Node modules need more.
// - ProcSubset=pid: apps read /proc/meminfo and /proc/cpuinfo.
// - PrivateNetwork/IPAddressDeny: sites talk to MariaDB, Redis and remote APIs.

import type { Account, OsProfile, RenderedFile, ResourceLimits } from '@xpanel/core'
import { cronToOnCalendar } from './cron.ts'
import { accountSliceName, sliceBodyLines, SYSTEMD_UNIT_DIR, type CgroupControllers } from './slice.ts'
import {
  assertAbsPath,
  assertAccountHome,
  assertAccountIdentity,
  assertHomeBase,
  assertInt,
  assertNoControl,
  assertPhpVersion,
  assertPort,
  assertShortName,
  assertUsername,
  invalid,
  type AccountIdentity,
} from './validate.ts'

export const XPANEL_CONFIG_ROOT = '/etc/xpanel'
/** Root-only EnvironmentFiles of Node/Python apps, one directory per account. */
export const APP_ENV_DIR = `${XPANEL_CONFIG_ROOT}/apps`
export const SH_BINARY = '/bin/sh'

export interface UnitOptions {
  /** os.paths.systemdDir is used when omitted */
  systemdDir?: string
  /** allowed home bases; defaults to /home and /home0..99. Every listed base is hidden from the unit. */
  homeBases?: string[]
}

type AccountRef = Pick<Account, 'username' | 'uid' | 'gid' | 'home'>

interface Ctx extends AccountIdentity {
  home: string
  /** home bases other than /home that the unit must not see (ProtectHome= covers /home) */
  hiddenBases: string[]
  slice: string
  systemdDir: string
}

const context = (account: AccountRef, os: OsProfile, opts: UnitOptions): Ctx => {
  const id = assertAccountIdentity(account, os)
  const { home, base } = assertAccountHome(account.home, id.username, opts.homeBases)
  const bases = new Set([base, ...(opts.homeBases ?? []).map(assertHomeBase)])
  // a tmpfs over /srv would leave no mount point for a second one over /srv/homes
  for (const a of bases) {
    for (const b of bases) if (b.startsWith(`${a}/`)) invalid(`home bases ${a} and ${b} are nested`, { bases: [a, b] })
  }
  bases.delete('/home')
  return {
    ...id,
    home,
    hiddenBases: [...bases].sort(),
    slice: accountSliceName(id.uid),
    systemdDir: assertAbsPath('systemdDir', opts.systemdDir ?? os.paths.systemdDir),
  }
}

interface IsolationExtras {
  /** already validated absolute paths */
  writable?: string[]
  /** Node's os.networkInterfaces() needs netlink */
  netlink?: boolean
}

/** Isolation shared by every account unit. */
const isolation = (ctx: Ctx, extras: IsolationExtras = {}): string[] => [
  `User=${ctx.username}`,
  `Group=${ctx.username}`,
  `Slice=${ctx.slice}`,
  'UMask=0027',
  'PrivateTmp=yes',
  'PrivateDevices=yes',
  'ProtectSystem=strict',
  'ProtectHome=tmpfs',
  // ProtectHome covers /home only; every other home base gets the same empty tmpfs so no other
  // account's home is even visible. BindPaths then brings back the account's own home.
  ...ctx.hiddenBases.map((b) => `TemporaryFileSystem=${b}:ro`),
  `BindPaths=${ctx.home}`,
  `ReadWritePaths=${[ctx.home, ...(extras.writable ?? [])].join(' ')}`,
  'ProtectProc=invisible',
  'ProtectKernelTunables=yes',
  'ProtectKernelModules=yes',
  'ProtectKernelLogs=yes',
  'ProtectControlGroups=yes',
  'ProtectClock=yes',
  'ProtectHostname=yes',
  'NoNewPrivileges=yes',
  'RestrictSUIDSGID=yes',
  'RestrictNamespaces=yes',
  'RestrictRealtime=yes',
  'LockPersonality=yes',
  `RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6${extras.netlink ? ' AF_NETLINK' : ''}`,
  'SystemCallArchitectures=native',
  'CapabilityBoundingSet=',
  'AmbientCapabilities=',
]

/**
 * No listening TCP port at all (cgroup BPF, systemd >= 249): an account process must never take the
 * loopback port that Apache proxies to for another account's app. UDP stays open for clients that
 * bind ephemeral ports (DNS resolvers, QUIC).
 */
const NO_TCP_LISTEN = ['SocketBindAllow=udp', 'SocketBindDeny=any']

const header = (what: string): string => `# Generated by xPanel (${what}). Manual edits are overwritten.`

const unitFile = (path: string, sections: (string | string[])[]): RenderedFile => ({
  path,
  content: `${sections.flat().join('\n')}\n`,
  mode: 0o644,
  owner: 'root',
  group: 'root',
})

/**
 * Quotes one ExecStart= word (systemd.service(5) "Command lines"): C escapes inside double quotes,
 * `$$` for a literal dollar (no env expansion) and `%%` for a literal percent (no specifiers).
 */
export const quoteExecArg = (arg: string): string =>
  `"${arg.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%').replace(/\$/g, '$$$$')}"`

/** Quotes one Environment= assignment. Environment= never expands `$`, but does expand `%`. */
const quoteEnvAssignment = (key: string, value: string): string =>
  `"${`${key}=${value}`.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%')}"`

// ---------------------------------------------------------------- PHP-FPM

export interface FpmUnitOptions extends UnitOptions {
  /** php-fpm binary; derivePhpFpmBinary(os, version) when omitted */
  fpmBinary?: string
  limitNofile?: number
}

export interface FpmPaths {
  unit: string
  /** php-fpm.conf of the master (--fpm-config) */
  config: string
  /** the pool the master includes */
  pool: string
  /** relative to /run, as RuntimeDirectory= wants it */
  runtimeDirectory: string
  socketDir: string
  socket: string
  /** relative to /var/log, as LogsDirectory= wants it */
  logsDirectory: string
  logDir: string
}

export const fpmUnitName = (username: string, version: string): string => `xpanel-php-fpm-${username}-${version}.service`

const FPM_LOGS_DIRECTORY = 'xpanel/php-fpm'

/** Shared by all PHP versions of one account. */
export const fpmAccountLogDir = (username: string): string => `/var/log/${FPM_LOGS_DIRECTORY}/${assertUsername(username)}`

/**
 * The one definition of where an account's FPM master keeps config, socket and logs; the edge
 * renderers (master, pool, Apache proxy_fcgi) read it from here. Configs share a per-version root-owned
 * directory, each file readable by its account only. Socket and pid live in the unit's
 * RuntimeDirectory, owned by the account, so no shared writable directory exists where one account
 * could pre-create another account's socket.
 */
export const fpmPaths = (username: string, version: string): FpmPaths => {
  const user = assertUsername(username)
  const v = assertPhpVersion(version)
  const runtimeDirectory = `xpanel/fpm/${user}-${v}`
  const logsDirectory = `${FPM_LOGS_DIRECTORY}/${user}`
  const socketDir = `/run/${runtimeDirectory}`
  return {
    unit: fpmUnitName(user, v),
    config: `${XPANEL_CONFIG_ROOT}/php-fpm/${v}/${user}.conf`,
    pool: `${XPANEL_CONFIG_ROOT}/php-fpm/${v}/${user}.pool.conf`,
    runtimeDirectory,
    socketDir,
    socket: `${socketDir}/php-fpm.sock`,
    logsDirectory,
    logDir: `/var/log/${logsDirectory}`,
  }
}

type FpmBinaryProfile = OsProfile & { phpFpmBinary?: (version: string) => string }

/**
 * The profile's own phpFpmBinary(version) when packages/os provides one. Otherwise php-fpm sits beside
 * the CLI binary in the same prefix: <prefix>/bin/php<suffix> -> <prefix>/sbin/php-fpm<suffix>, which
 * holds for Debian/Ondrej (/usr/bin/php8.3), Remi (/opt/remi/php83/root/usr/bin/php) and our own builds
 * (/opt/xpanel/php/8.3/bin/php).
 */
export const derivePhpFpmBinary = (os: OsProfile, version: string): string => {
  const v = assertPhpVersion(version)
  const own = (os as FpmBinaryProfile).phpFpmBinary
  if (typeof own === 'function') return assertAbsPath('php-fpm binary', own(v))
  const cli = assertAbsPath('php binary', os.phpBinary(v))
  const m = /^(.*\/)bin\/php([0-9.]*)$/.exec(cli)
  if (!m) return invalid(`cannot derive php-fpm from ${cli}; pass fpmBinary`, { cli })
  return `${m[1]}sbin/php-fpm${m[2]}`
}

export const renderFpmUnit = (account: AccountRef, version: string, os: OsProfile, opts: FpmUnitOptions = {}): RenderedFile => {
  const ctx = context(account, os, opts)
  const v = assertPhpVersion(version)
  const p = fpmPaths(ctx.username, v)
  const binary = assertAbsPath('fpmBinary', opts.fpmBinary ?? derivePhpFpmBinary(os, v))
  const nofile = assertInt('limitNofile', opts.limitNofile ?? 65536, 1024, 1048576)
  return unitFile(`${ctx.systemdDir}/${p.unit}`, [
    header(`PHP ${v} FPM for ${ctx.username}`),
    '[Unit]',
    `Description=xPanel PHP-FPM ${v} for ${ctx.username}`,
    'After=network.target',
    '',
    '[Service]',
    'Type=notify',
    `ExecStart=${binary} --nodaemonize --fpm-config ${p.config}`,
    'ExecReload=/bin/kill -USR2 $MAINPID',
    'Restart=on-failure',
    'RestartSec=2s',
    `RuntimeDirectory=${p.runtimeDirectory}`,
    'RuntimeDirectoryMode=0750',
    `LogsDirectory=${p.logsDirectory}`,
    'LogsDirectoryMode=0750',
    `LimitNOFILE=${nofile}`,
    // PHP listens on its unix socket only.
    ...NO_TCP_LISTEN,
    ...isolation(ctx, { writable: [p.socketDir, p.logDir] }),
    '',
    '[Install]',
    'WantedBy=multi-user.target',
  ])
}

// ---------------------------------------------------------------- Node / Python apps

export interface AppSpec {
  name: string
  kind: 'node' | 'python'
  /** loopback port the app listens on; Apache proxies to it */
  port: number
  /** argv; argv[0] is an absolute path to the interpreter or launcher */
  execStart: string[]
  /** absolute path inside the account home */
  workingDir: string
  /** private settings, written to a root-only EnvironmentFile (never visible via `systemctl show`) */
  env?: Record<string, string>
}

export interface AppUnitOptions extends UnitOptions {
  /** ports the app may not take: panel, backend, ssh ... */
  reservedPorts?: number[]
}

export interface RenderedApp {
  unit: RenderedFile
  envFile: RenderedFile
}

const RESERVED_ENV = new Set(['PORT', 'HOST'])

export const appUnitName = (username: string, app: string): string => `xpanel-app-${username}-${app}.service`

export const appEnvDir = (username: string): string => `${APP_ENV_DIR}/${assertUsername(username)}`

const insideHome = (ctx: Ctx, what: string, p: unknown): string => {
  const path = assertAbsPath(what, p)
  if (path !== ctx.home && !path.startsWith(`${ctx.home}/`)) return invalid(`${what} must be inside the account home`, { path })
  return path
}

/** EnvironmentFile= value: single quotes are literal; otherwise double quotes with shell escapes. */
const envFileValue = (value: string): string =>
  value.includes("'") ? `"${value.replace(/[\\"`$]/g, (c) => `\\${c}`)}"` : `'${value}'`

export const renderAppUnit = (account: AccountRef, app: AppSpec, os: OsProfile, opts: AppUnitOptions = {}): RenderedApp => {
  const ctx = context(account, os, opts)
  const name = assertShortName('app name', app.name)
  if (app.kind !== 'node' && app.kind !== 'python') return invalid('app kind must be node or python', { kind: app.kind })
  const port = assertInt('app port', app.port, 1024, 65535)
  if ((opts.reservedPorts ?? []).map((p) => assertPort('reserved port', p)).includes(port)) {
    return invalid(`port ${port} is reserved`, { port })
  }
  if (!Array.isArray(app.execStart) || app.execStart.length === 0 || app.execStart.length > 64) {
    return invalid('execStart must hold 1-64 arguments')
  }
  const [exe, ...args] = app.execStart
  const binary = assertAbsPath('app executable', exe)
  const argv = args.map((a, i) => quoteExecArg(assertNoControl(`execStart[${i + 1}]`, a, 1024)))
  const workingDir = insideHome(ctx, 'workingDir', app.workingDir)

  const env = app.env ?? {}
  if (typeof env !== 'object' || env === null || Array.isArray(env)) return invalid('env must be an object')
  const envEntries = Object.entries(env)
  if (envEntries.length > 128) return invalid('at most 128 env variables')
  const envLines = envEntries.map(([k, v]) => {
    if (!/^[A-Za-z_][A-Za-z0-9_]{0,63}$/.test(k)) return invalid(`invalid env name ${JSON.stringify(k)}`)
    if (RESERVED_ENV.has(k)) return invalid(`${k} is set by xPanel`, { key: k })
    return `${k}=${envFileValue(assertNoControl(`env ${k}`, v, 4096))}`
  })

  const unit = appUnitName(ctx.username, name)
  const envPath = `${appEnvDir(ctx.username)}/${name}.env`
  const unitText = unitFile(`${ctx.systemdDir}/${unit}`, [
    header(`${app.kind} app ${name} for ${ctx.username}`),
    '[Unit]',
    `Description=xPanel ${app.kind} app ${name} for ${ctx.username}`,
    'After=network.target',
    '',
    '[Service]',
    'Type=simple',
    `WorkingDirectory=${workingDir}`,
    `Environment=${quoteEnvAssignment('PORT', String(port))} ${quoteEnvAssignment('HOST', '127.0.0.1')}`,
    ...(app.kind === 'python' ? [`Environment=${quoteEnvAssignment('PYTHONUNBUFFERED', '1')}`] : []),
    `EnvironmentFile=${envPath}`,
    `ExecStart=${[binary, ...argv].join(' ')}`,
    'Restart=on-failure',
    'RestartSec=2s',
    // TCP: the app may bind its own port and nothing else.
    `SocketBindAllow=tcp:${port}`,
    ...NO_TCP_LISTEN,
    'LimitNOFILE=65536',
    ...isolation(ctx, { netlink: true }),
    '',
    '[Install]',
    'WantedBy=multi-user.target',
  ])
  const envFile: RenderedFile = {
    path: envPath,
    content: `${header(`env for app ${name} of ${ctx.username}`)}\n${envLines.map((l) => `${l}\n`).join('')}`,
    mode: 0o600,
    owner: 'root',
    group: 'root',
  }
  return { unit: unitText, envFile }
}

// ---------------------------------------------------------------- Cron as timers

export interface CronJob {
  /** stable id, used in unit names */
  id: string
  /** 5-field crontab schedule or an @macro */
  schedule: string
  /** shell command line, run by /bin/sh -c as the account; `%` is literal, unlike crontab */
  command: string
  /** optional cap on one run; infinity when omitted */
  maxRuntimeSec?: number
}

export interface RenderedCron {
  serviceName: string
  timerName: string
  onCalendar: string[]
  service: RenderedFile
  timer: RenderedFile
}

export const cronUnitNames = (username: string, id: string): { service: string; timer: string } => ({
  service: `xpanel-cron-${username}-${id}.service`,
  timer: `xpanel-cron-${username}-${id}.timer`,
})

export const renderCronUnits = (account: AccountRef, job: CronJob, os: OsProfile, opts: UnitOptions = {}): RenderedCron => {
  const ctx = context(account, os, opts)
  const id = assertShortName('cron job id', job.id)
  const onCalendar = cronToOnCalendar(job.schedule)
  const command = assertNoControl('cron command', job.command, 4096)
  if (command.trim() === '') return invalid('cron command is empty')
  const timeout = job.maxRuntimeSec === undefined ? 'infinity' : `${assertInt('maxRuntimeSec', job.maxRuntimeSec, 1, 7 * 86400)}s`
  const names = cronUnitNames(ctx.username, id)

  const service = unitFile(`${ctx.systemdDir}/${names.service}`, [
    header(`cron job ${id} for ${ctx.username}`),
    '[Unit]',
    `Description=xPanel cron job ${id} for ${ctx.username}`,
    '',
    '[Service]',
    'Type=oneshot',
    `WorkingDirectory=${ctx.home}`,
    `Environment=${quoteEnvAssignment('PATH', '/usr/local/bin:/usr/bin:/bin')}`,
    `ExecStart=${SH_BINARY} -c ${quoteExecArg(command)}`,
    `TimeoutStartSec=${timeout}`,
    // a job may not start a listener that squats another account's app port
    ...NO_TCP_LISTEN,
    ...isolation(ctx),
  ])
  const timer = unitFile(`${ctx.systemdDir}/${names.timer}`, [
    header(`cron schedule ${id} for ${ctx.username}`),
    '[Unit]',
    `Description=xPanel cron schedule ${id} for ${ctx.username}`,
    '',
    '[Timer]',
    ...onCalendar.map((c) => `OnCalendar=${c}`),
    'AccuracySec=1s',
    'Persistent=false',
    `Unit=${names.service}`,
    '',
    '[Install]',
    'WantedBy=timers.target',
  ])
  return { serviceName: names.service, timerName: names.timer, onCalendar, service, timer }
}

// ---------------------------------------------------------------- logind sessions

export interface LoginDropinOptions {
  systemdDir?: string
  controllers?: CgroupControllers
}

export const loginSliceDropinPath = (uid: number, systemdDir = SYSTEMD_UNIT_DIR): string =>
  `${systemdDir}/user-${uid}.slice.d/50-xpanel.conf`

/**
 * SSH and other logind sessions land in user-<uid>.slice, not in xpanel-<uid>.slice. This drop-in
 * mirrors the plan limits there. It is a separate budget: one account may use the plan once in its
 * services and once more in its shell sessions. Unlimited is written as `infinity` so logind's own
 * defaults (e.g. TasksMax=33%) are overridden explicitly.
 */
export const renderLoginSliceDropin = (
  account: Pick<Account, 'username' | 'uid' | 'gid'>,
  resources: ResourceLimits,
  ioDevices: readonly unknown[] = [],
  opts: LoginDropinOptions = {},
): RenderedFile => {
  const id = assertAccountIdentity(account)
  const systemdDir = assertAbsPath('systemdDir', opts.systemdDir ?? SYSTEMD_UNIT_DIR)
  const lines = sliceBodyLines(resources, ioDevices, opts.controllers ? { controllers: opts.controllers } : {})
  return unitFile(loginSliceDropinPath(id.uid, systemdDir), [
    header(`login sessions of ${id.username}`),
    `# Mirrors the limits of ${accountSliceName(id.uid)} for logind sessions (SSH). Separate budget, same caps.`,
    '[Slice]',
    ...lines,
  ])
}

export interface FpmUnitIsolationProof {
  unit: string
  slice: string
  user: string
  group: string
  runtimeDirectory: string
  runtimeDirectoryMode: string
  socketPath: string
  bindPaths: string[]
  noNewPrivileges: boolean
  privateTmp: boolean
  protectHome: string
  protectSystem: string
  tcpListenDenied: boolean
}

const unitKeyValues = (content: string, key: string): string[] =>
  content
    .split('\n')
    .filter((l) => l.startsWith(`${key}=`))
    .map((l) => l.slice(key.length + 1))

/**
 * Verifies that a rendered PHP-FPM systemd unit strictly binds the master and all worker
 * processes to `xpanel-<uid>.slice`, `<user>:<user>`, an account-owned `0750` RuntimeDirectory,
 * and a mount namespace that hides other accounts' homes while forbidding TCP port squatting.
 */
export const verifyFpmUnitIsolation = (
  account: AccountRef,
  version: string,
  unit: RenderedFile,
  os?: OsProfile,
  opts: UnitOptions = {},
): FpmUnitIsolationProof => {
  const ctx = os
    ? context(account, os, opts)
    : (() => {
        const id = assertAccountIdentity(account)
        const { home } = assertAccountHome(account.home, id.username, opts.homeBases)
        return {
          ...id,
          home,
          hiddenBases: [],
          slice: accountSliceName(id.uid),
          systemdDir: assertAbsPath('systemdDir', opts.systemdDir ?? SYSTEMD_UNIT_DIR),
        }
      })()
  const v = assertPhpVersion(version)
  const p = fpmPaths(ctx.username, v)
  const c = unit.content

  const user = unitKeyValues(c, 'User')[0]
  const group = unitKeyValues(c, 'Group')[0]
  const slice = unitKeyValues(c, 'Slice')[0]
  const runtimeDirectory = unitKeyValues(c, 'RuntimeDirectory')[0]
  const runtimeDirectoryMode = unitKeyValues(c, 'RuntimeDirectoryMode')[0]
  const protectHome = unitKeyValues(c, 'ProtectHome')[0]
  const protectSystem = unitKeyValues(c, 'ProtectSystem')[0]
  const noNewPrivileges = unitKeyValues(c, 'NoNewPrivileges')[0] === 'yes'
  const privateTmp = unitKeyValues(c, 'PrivateTmp')[0] === 'yes'
  const bindPaths = unitKeyValues(c, 'BindPaths')
  const socketBindAllow = unitKeyValues(c, 'SocketBindAllow')
  const socketBindDeny = unitKeyValues(c, 'SocketBindDeny')

  if (user !== ctx.username || group !== ctx.username) {
    return invalid('PHP-FPM unit User/Group must match the account identity', { user, group, expected: ctx.username })
  }
  if (slice !== ctx.slice) {
    return invalid('PHP-FPM unit Slice must match the account slice', { slice, expected: ctx.slice })
  }
  if (runtimeDirectory !== p.runtimeDirectory || runtimeDirectoryMode !== '0750') {
    return invalid('PHP-FPM unit RuntimeDirectory must be account-scoped mode 0750', {
      runtimeDirectory,
      runtimeDirectoryMode,
    })
  }
  if (!noNewPrivileges || !privateTmp || protectHome !== 'tmpfs' || protectSystem !== 'strict') {
    return invalid('PHP-FPM unit is missing mandatory systemd sandboxing directives', {
      noNewPrivileges,
      privateTmp,
      protectHome,
      protectSystem,
    })
  }
  if (!bindPaths.includes(ctx.home)) {
    return invalid('PHP-FPM unit BindPaths must mount the account home', { bindPaths, expected: ctx.home })
  }
  const tcpListenDenied = socketBindAllow.includes('udp') && !socketBindAllow.some((a) => a.startsWith('tcp')) && socketBindDeny.includes('any')
  if (!tcpListenDenied) {
    return invalid('PHP-FPM unit must deny TCP port binding', { socketBindAllow, socketBindDeny })
  }

  return {
    unit: p.unit,
    slice,
    user,
    group,
    runtimeDirectory,
    runtimeDirectoryMode,
    socketPath: p.socket,
    bindPaths,
    noNewPrivileges,
    privateTmp,
    protectHome,
    protectSystem,
    tcpListenDenied,
  }
}
