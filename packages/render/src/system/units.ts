export interface FpmUnitOptions extends UnitOptions {
  /** php-fpm binary; derivePhpFpmBinary(os, version) when omitted */
  fpmBinary?: string
  limitNofile?: number
}

export interface FpmPaths {
  unit: string
  /** php-fpm.conf of the master (--fpm-config) */
  config: string
  /** the pool the master includes */
  pool: string
  /** relative to /run, as RuntimeDirectory= wants it */
  runtimeDirectory: string
  socketDir: string
  socket: string
  /** relative to /var/log, as LogsDirectory= wants it */
  logsDirectory: string
  logDir: string
}

export const fpmUnitName = (username: string, version: string): string => `xpanel-php-fpm-${username}-${version}.service`

const FPM_LOGS_DIRECTORY = 'xpanel/php-fpm'

/** Shared by all PHP versions of one account. */
export const fpmAccountLogDir = (username: string): string => `/var/log/${FPM_LOGS_DIRECTORY}/${assertUsername(username)}`

/**
 * The one definition of where an account's FPM master keeps config, socket and logs; the edge
 * renderers (master, pool, Apache proxy_fcgi) read it from here. Configs share a per-version root-owned
 * directory, each file readable by its account only. Socket and pid live in the unit's
 * RuntimeDirectory, owned by the account, so no shared writable directory exists where one account
 * could pre-create another account's socket.
 */
export const fpmPaths = (username: string, version: string): FpmPaths => {
  const user = assertUsername(username)
  const v = assertPhpVersion(version)
  const runtimeDirectory = `xpanel-fpm/${user}-${v}`
  const logsDirectory = `${FPM_LOGS_DIRECTORY}/${user}`
  const socketDir = `/run/${runtimeDirectory}`
  return {
    unit: fpmUnitName(user, v),
    config: `${XPANEL_CONFIG_ROOT}/php-fpm/${v}/${user}.conf`,
    pool: `${XPANEL_CONFIG_ROOT}/php-fpm/${v}/${user}.pool.conf`,
    runtimeDirectory,
    socketDir,
    socket: `${socketDir}/php-fpm.sock`,
    logsDirectory,
    logDir: `/var/log/${logsDirectory}`,
  }
}

type FpmBinaryProfile = OsProfile & { phpFpmBinary?: (version: string) => string }

/**
 * The profile's own phpFpmBinary(version) when packages/os provides one. Otherwise php-fpm sits beside
 * the CLI binary in the same prefix: <prefix>/bin/php<suffix> -> <prefix>/sbin/php-fpm<suffix>, which
 * holds for Debian/Ondrej (/usr/bin/php8.3), Remi (/opt/remi/php83/root/usr/bin/php) and our own builds
 * (/opt/xpanel/php/8.3/bin/php).
 */
export const derivePhpFpmBinary = (os: OsProfile, version: string): string => {
  const v = assertPhpVersion(version)
  const own = (os as FpmBinaryProfile).phpFpmBinary
  if (typeof own === 'function') return assertAbsPath('php-fpm binary', own(v))
  const cli = assertAbsPath('php binary', os.phpBinary(v))
  const m = /^(.*\/)bin\/php([0-9.]*)$/.exec(cli)
  if (!m) return invalid(`cannot derive php-fpm from ${cli}; pass fpmBinary`, { cli })
  return `${m[1]}sbin/php-fpm${m[2]}`
}

export const renderFpmUnit = (account: AccountRef, version: string, os: OsProfile, opts: FpmUnitOptions = {}): RenderedFile => {
  const ctx = context(account, os, opts)
  const v = assertPhpVersion(version)
  const p = fpmPaths(ctx.username, v)
  const binary = assertAbsPath('fpmBinary', opts.fpmBinary ?? derivePhpFpmBinary(os, v))
  const nofile = assertInt('limitNofile', opts.limitNofile ?? 65536, 1024, 1048576)
  return unitFile(`${ctx.systemdDir}/${p.unit}`, [
    header(`PHP ${v} FPM for ${ctx.username}`),
    '[Unit]',
    `Description=xPanel PHP-FPM ${v} for ${ctx.username}`,
    'After=network.target',
    '',
    '[Service]',
    'Type=notify',
    `ExecStart=${binary} --nodaemonize --fpm-config ${p.config}`,
    'ExecReload=/bin/kill -USR2 $MAINPID',
    'Restart=on-failure',
    'RestartSec=2s',
    `RuntimeDirectory=${p.runtimeDirectory}`,
    'RuntimeDirectoryMode=0750',
    `LogsDirectory=${p.logsDirectory}`,
    'LogsDirectoryMode=0750',
    `LimitNOFILE=${nofile}`,
    // PHP listens on its unix socket only.
    ...NO_TCP_LISTEN,
    ...isolation(ctx, { writable: [p.socketDir, p.logDir] }),
    '',
    '[Install]',
    'WantedBy=multi-user.target',
  ])
}

