import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// Pure text rendering only. The caller must separately prove the release, runtime,
// unit ownership and mutation authority before writing or activating these bytes.
export const MANAGED_UNIT_NAMES = Object.freeze([
  'xpanel.slice', 'xpanel-agent.service', 'xpanel-api.service',
  'xpanel-management-tls.service', 'xpanel-management-tls.timer',
])
const fail = code => { throw Object.assign(new Error(code), { code }) }
const safeExecutable = value => typeof value === 'string' && value.length <= 4096
  && /^\/(?:[A-Za-z0-9_.-]+\/)*[A-Za-z0-9_.-]+$/.test(value)
  && !value.split('/').some(part => part === '.' || part === '..')
const releaseRoot = value => typeof value === 'string'
  && /^\/opt\/xpanel\/releases\/(0|[1-9][0-9]{0,8})\.(0|[1-9][0-9]{0,8})\.(0|[1-9][0-9]{0,8})$/.test(value)
// API heap arguments, current first, then each one an installed release still runs. A new release parses the transition
// journal and observes the writers an installed release left behind, so removing a vector refuses upgrades from it.
// --max-semi-space-size=1 (0.1.48): Node 26 grows the young generation to ~56 MB beside the 96 MB old space.
// --max-old-space-size=160 --max-semi-space-size=2: keeps full route/catalog evaluation comfortably inside the API heap.
export const API_HEAP_ARGUMENTS = Object.freeze([
  Object.freeze(['--max-old-space-size=160', '--max-semi-space-size=2']),
  Object.freeze(['--max-old-space-size=96', '--max-semi-space-size=1']),
  Object.freeze(['--max-old-space-size=96']),
])

function render(options, plan, apiHeap = API_HEAP_ARGUMENTS[0]) {
  const keys = ['nodePath', 'programRoot', 'lifecycleParticipants']
  if (!options || typeof options !== 'object' || Array.isArray(options)
    || ![Object.prototype, null].includes(Object.getPrototypeOf(options))
    || Reflect.ownKeys(options).length !== keys.length
    || !Reflect.ownKeys(options).every(key => keys.includes(key)
      && Object.hasOwn(Object.getOwnPropertyDescriptor(options, key) ?? {}, 'value'))) fail('UNIT_OPTIONS_INVALID')
  const { nodePath, programRoot, lifecycleParticipants } = options
  if (!safeExecutable(nodePath)) fail('NODE_PATH_INVALID')
  if (programRoot !== '/opt/xpanel' && !releaseRoot(programRoot)
    && !(plan && programRoot === '/opt/xpanel/current')) fail('PROGRAM_ROOT_INVALID')
  if (typeof lifecycleParticipants !== 'boolean') fail('UNIT_PARTICIPANTS_INVALID')
  const participantPre = lifecycleParticipants
    ? '\nExecStartPre=/usr/bin/install -d -o root -g root -m 0700 /run/xpanel/lifecycle-agent\nExecStartPre=/usr/bin/install -d -o xpanel -g xpanel -m 0700 /run/xpanel/lifecycle-api' : ''
  const participantWrite = lifecycleParticipants ? ' /run/xpanel/lifecycle-api' : ''
  return Object.freeze({
    'xpanel.slice': `# Generated by xPanel: parent cgroup v2 slice for all tenant account slices (xpanel-<uid>.slice)
[Unit]
Description=xPanel Multi-Tenant Account Hierarchy Slice
Documentation=man:systemd.resource-control(5)
Before=slices.target

[Slice]
CPUAccounting=yes
MemoryAccounting=yes
IOAccounting=yes
TasksAccounting=yes
`,
    'xpanel-agent.service': `[Unit]
Description=xPanel Privileged Host Reconciler & Isolation Agent
After=network-online.target systemd-sysctl.service systemd-tmpfiles-setup.service
Wants=network-online.target

[Service]
Type=simple
User=root
Group=xpanel-agent
SupplementaryGroups=xpanel
RuntimeDirectory=xpanel
RuntimeDirectoryMode=0750
RuntimeDirectoryPreserve=no
WorkingDirectory=${programRoot}
Environment=NODE_ENV=production
EnvironmentFile=/etc/xpanel/runtime.env
Environment=XPANEL_GENERATIONS_DIR=/var/lib/xpanel/generations
Environment=XPANEL_LOG_DIR=/var/log/xpanel
Environment=XPANEL_RUN_DIR=/run/xpanel
ExecStartPre=/usr/bin/test -f /var/lib/xpanel/control.db${participantPre}
ExecStart=${nodePath} --max-old-space-size=64 ${programRoot}/apps/agent/src/main.ts
Restart=always
RestartSec=2
UMask=0007

[Install]
WantedBy=multi-user.target
`,
    'xpanel-api.service': `[Unit]
Description=xPanel Control Plane API (xPanel / xWHM / xMail private backends)
After=network-online.target xpanel-agent.service
Requires=xpanel-agent.service

[Service]
Type=simple
User=xpanel
Group=xpanel
SupplementaryGroups=xpanel-agent
WorkingDirectory=${programRoot}
Environment=NODE_ENV=production
EnvironmentFile=/etc/xpanel/runtime.env
EnvironmentFile=/etc/xpanel/api.env
ExecStart=${nodePath} ${apiHeap.join(' ')} ${programRoot}/apps/api/src/main.ts
RuntimeDirectory=xpanel-api
RuntimeDirectoryMode=0755
Restart=always
RestartSec=2
UMask=0007
NoNewPrivileges=yes
PrivateTmp=yes
ProtectHome=yes
ProtectSystem=strict
ReadWritePaths=/var/lib/xpanel /var/log/xpanel${participantWrite}
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
CapabilityBoundingSet=
AmbientCapabilities=
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6

[Install]
WantedBy=multi-user.target
`,
    'xpanel-management-tls.service': `# Managed by xPanel management TLS lifecycle v1.
[Unit]
Description=xPanel management TLS renewal and served-certificate verification
After=network-online.target nginx.service
Wants=network-online.target

[Service]
Type=oneshot
User=root
Group=root
UMask=0077
ExecStart=${nodePath} ${programRoot}/scripts/management-tls.mjs renew
SuccessExitStatus=75
TimeoutStartSec=720
TimeoutStopSec=10
KillMode=control-group
NoNewPrivileges=yes
PrivateTmp=yes
ProtectHome=yes

`,
    'xpanel-management-tls.timer': `# Managed by xPanel management TLS lifecycle v1.
[Unit]
Description=xPanel management TLS renewal schedule

[Timer]
OnCalendar=*-*-* 00,12:00:00
RandomizedDelaySec=1h
Persistent=true
Unit=xpanel-management-tls.service

[Install]
WantedBy=timers.target
`,
  })
}

/** Exact installed release or legacy flat layout; never a movable current link. */
export const renderManagedUnits = options => render(options, false)

/** Every unit image a supported release renders for these options, current first; validates images an installed release wrote. */
export const renderInstalledManagedUnitImages = options => API_HEAP_ARGUMENTS.map(heap => render(options, false, heap))

/** Exact argv a managed writer daemon runs with under the current or an installed release's unit. */
export const managedWriterArguments = (role, nodePath, entry) =>
  (role === 'agent' ? [['--max-old-space-size=64']] : API_HEAP_ARGUMENTS).map(heap => [nodePath, ...heap, entry])

/** Diagnostic preview before an authenticated release version is available. */
export const renderManagedUnitPlan = options => render(options, true)

/** CLI writes one selected unit to stdout, never to a host path. */
export function runManagedUnitCli(args, io = process) {
  try {
    if (!Array.isArray(args) || args.length !== 5) fail('UNIT_ARGUMENTS_INVALID')
    const [mode, unit, ...settings] = args
    if (!['render', 'plan'].includes(mode) || !MANAGED_UNIT_NAMES.includes(unit)) fail('UNIT_ARGUMENTS_INVALID')
    const values = Object.create(null)
    for (const setting of settings) {
      const match = typeof setting === 'string' && /^(--node-path|--program-root|--participants)=(.+)$/.exec(setting)
      if (!match || Object.hasOwn(values, match[1])) fail('UNIT_ARGUMENTS_INVALID')
      values[match[1]] = match[2]
    }
    if (!['0', '1'].includes(values['--participants'])) fail('UNIT_ARGUMENTS_INVALID')
    const options = { nodePath: values['--node-path'], programRoot: values['--program-root'], lifecycleParticipants: values['--participants'] === '1' }
    const units = mode === 'plan' ? renderManagedUnitPlan(options) : renderManagedUnits(options)
    io.stdout.write(units[unit])
    return 0
  } catch {
    io.stderr.write('Managed unit rendering failed.\n')
    return 1
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = runManagedUnitCli(process.argv.slice(2))
}
