import { generateKeyPairSync, randomUUID } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import type { UpgradeProcessBinding } from './upgrade-coordinator-contract.ts'
import {
  decodeUpgradeIpcFrame, encodeUpgradeIpcFrame, parseLauncherKeyPair, parseUpgradeIpcRequest, parseUpgradeIpcResponse,
  signUpgradeIpcResponse, UPGRADE_IPC_LIMIT, verifyUpgradeIpcResponse,
  type UpgradeIpcRequest, type UpgradeLauncherIdentity,
} from './ops-upgrade-ipc.ts'

// Portable cryptographic protocol tests only. No systemd, SO_PEERCRED, hosted UID or native-upgrade proof.
const keys = generateKeyPairSync('ed25519')
const identity: UpgradeLauncherIdentity = {
  workerId: 'upgrade-coordinator-' + randomUUID(), pid: 1234, start: '987654', bootId: randomUUID(), receiptSha256: 'a'.repeat(64),
}
const { workerId: _workerId, ...observed } = identity
const binding: UpgradeProcessBinding = {
  jobId: randomUUID(), requestFingerprint: 'b'.repeat(64), referenceCode: 'XP-JOB-2026-000001',
  // This is the durable lease owner, independently generated by DurableUpgradeCoordinator.
  workerId: 'upgrade-coordinator-' + randomUUID(), fencingToken: 7,
}
const qualification = { digest: 'd'.repeat(64), observedAt: '2026-11-03T00:00:00.000Z' }
const hello = (): UpgradeIpcRequest => ({ kind: 'hello', nonce: randomUUID() })
const dispatch = (): Extract<UpgradeIpcRequest, { kind: 'dispatch' }> => ({ kind: 'dispatch', nonce: randomUUID(), binding })

describe('authenticated upgrade IPC protocol', () => {
  it('authenticates a fresh nonce together with the actual process lifetime and receipt', () => {
    const request = hello()
    const signed = signUpgradeIpcResponse({ kind: 'ready', nonce: request.nonce, identity, binding: null, qualification }, keys.privateKey)
    expect(verifyUpgradeIpcResponse(decodeUpgradeIpcFrame(encodeUpgradeIpcFrame(signed)), request, observed, keys.publicKey)).toEqual(signed)
    // Property insertion order is not part of the kernel/process observation contract.
    expect(verifyUpgradeIpcResponse(signed, request, { receiptSha256: observed.receiptSha256, bootId: observed.bootId, start: observed.start, pid: observed.pid }, keys.publicKey)).toEqual(signed)
  })

  it('rejects an old nonce, a different peer lifetime, a changed receipt and a foreign signing key', () => {
    const request = hello()
    const signed = signUpgradeIpcResponse({ kind: 'ready', nonce: request.nonce, identity, binding: null, qualification }, keys.privateKey)
    expect(() => verifyUpgradeIpcResponse(signed, hello(), observed, keys.publicKey)).toThrow()
    for (const changed of [
      { ...observed, pid: observed.pid + 1 }, { ...observed, start: '987655' },
      { ...observed, bootId: randomUUID() }, { ...observed, receiptSha256: 'c'.repeat(64) },
    ]) expect(() => verifyUpgradeIpcResponse(signed, request, changed, keys.publicKey)).toThrow()
    expect(() => verifyUpgradeIpcResponse(signed, request, observed, generateKeyPairSync('ed25519').publicKey)).toThrow()
  })

  it('binds the acknowledgement to every durable handoff field', () => {
    const request = dispatch()
    const signed = signUpgradeIpcResponse({ kind: 'accepted', nonce: request.nonce, identity, binding, qualification }, keys.privateKey)
    expect(verifyUpgradeIpcResponse(signed, request, observed, keys.publicKey).binding).toEqual(binding)
    const substitutions: UpgradeProcessBinding[] = [
      { ...binding, jobId: randomUUID() }, { ...binding, requestFingerprint: 'c'.repeat(64) },
      { ...binding, referenceCode: 'XP-JOB-2026-000002' }, { ...binding, workerId: 'upgrade-coordinator-' + randomUUID() },
      { ...binding, fencingToken: binding.fencingToken + 1 },
    ]
    for (const substituted of substitutions) {
      expect(() => verifyUpgradeIpcResponse(signed, { ...request, binding: substituted }, observed, keys.publicKey)).toThrow()
      expect(() => verifyUpgradeIpcResponse({ ...signed, binding: substituted }, request, observed, keys.publicKey)).toThrow()
    }
  })

  it('refuses a valid readiness signature as a dispatch acknowledgement', () => {
    const request = dispatch()
    const signed = signUpgradeIpcResponse({ kind: 'ready', nonce: request.nonce, identity, binding: null, qualification }, keys.privateKey)
    expect(() => verifyUpgradeIpcResponse(signed, request, observed, keys.publicKey)).toThrow()
  })

  it('rejects mutations of the signed worker identity even when the kernel peer remains unchanged', () => {
    const request = hello()
    const signed = signUpgradeIpcResponse({ kind: 'ready', nonce: request.nonce, identity, binding: null, qualification }, keys.privateKey)
    expect(() => verifyUpgradeIpcResponse({ ...signed, identity: { ...identity, workerId: 'upgrade-coordinator-' + randomUUID() } }, request, observed, keys.publicKey)).toThrow()
    expect(() => verifyUpgradeIpcResponse({ ...signed, signature: Buffer.alloc(64).toString('base64') }, request, observed, keys.publicKey)).toThrow()
    expect(() => verifyUpgradeIpcResponse({ ...signed, qualification: { ...qualification, digest: 'e'.repeat(64) } }, request, observed, keys.publicKey)).toThrow()
    expect(() => verifyUpgradeIpcResponse({ ...signed, qualification: { available: true } }, request, observed, keys.publicKey)).toThrow()
  })

  it('admits only exact public request fields and exact process bindings', () => {
    expect(parseUpgradeIpcRequest(dispatch())).toMatchObject({ kind: 'dispatch', binding })
    for (const invalid of [
      { ...hello(), actor: 'root' }, { ...dispatch(), command: 'recover' }, { ...dispatch(), binding: { ...binding, archivePath: '/tmp/release' } },
      { ...dispatch(), binding: { ...binding, fencingToken: 0 } }, { ...dispatch(), binding: { ...binding, referenceCode: 'XP-JOB-2026-000000' } },
      { kind: 'hello', nonce: '' }, { kind: 'shell', nonce: randomUUID() },
    ]) expect(() => parseUpgradeIpcRequest(invalid)).toThrow()
  })

  it('rejects noncanonical process identity and unexpected acknowledgement fields', () => {
    const request = hello()
    const signed = signUpgradeIpcResponse({ kind: 'ready', nonce: request.nonce, identity, binding: null, qualification }, keys.privateKey)
    for (const invalid of [
      { ...signed, environment: {} }, { ...signed, binding }, { ...signed, signature: 'abc' },
      { ...signed, identity: { ...identity, pid: 1.5 } }, { ...signed, identity: { ...identity, pid: 0 } },
      { ...signed, identity: { ...identity, workerId: 'upgrade-coordinator-' + '-'.repeat(36) } },
      { ...signed, identity: { ...identity, command: 'upgrade' } },
    ]) expect(() => parseUpgradeIpcResponse(invalid)).toThrow()
  })
})

describe('bounded single-frame IPC transport', () => {
  it('rejects truncation, additional frames, CRLF, invalid UTF-8 and oversized input', () => {
    const frame = encodeUpgradeIpcFrame(hello())
    for (const invalid of [
      frame.subarray(0, -1), Buffer.concat([frame, frame]), Buffer.from('{}\r\n'),
      Buffer.from([0x22, 0xc0, 0xaf, 0x22, 0x0a]), Buffer.alloc(UPGRADE_IPC_LIMIT + 1, 10),
    ]) expect(() => decodeUpgradeIpcFrame(invalid)).toThrow()
    expect(() => encodeUpgradeIpcFrame({ oversized: 'x'.repeat(UPGRADE_IPC_LIMIT) })).toThrow()
  })

  it('requires a dedicated matching Ed25519 pair', () => {
    const privateBytes = Buffer.from(keys.privateKey.export({ type: 'pkcs8', format: 'pem' }))
    const publicBytes = Buffer.from(keys.publicKey.export({ type: 'spki', format: 'pem' }))
    expect(parseLauncherKeyPair(privateBytes, publicBytes).publicKey.asymmetricKeyType).toBe('ed25519')
    expect(() => parseLauncherKeyPair(privateBytes, privateBytes)).toThrow()
    const wrong = generateKeyPairSync('ed25519').publicKey.export({ type: 'spki', format: 'pem' })
    expect(() => parseLauncherKeyPair(privateBytes, Buffer.from(wrong))).toThrow()
    const ec = generateKeyPairSync('ec', { namedCurve: 'prime256v1' })
    expect(() => parseLauncherKeyPair(Buffer.from(ec.privateKey.export({ type: 'pkcs8', format: 'pem' })), Buffer.from(ec.publicKey.export({ type: 'spki', format: 'pem' })))).toThrow()
  })
})
